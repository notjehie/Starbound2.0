#!/usr/bin/env python3
"""
Build data/real_data.js from real TESS observations of TOI-700 (TIC 150428135).

STATUS: NOT YET RUN. This script was written without network access to MAST, so
it has not been executed or validated. Check its output before relying on it.

What it does
  1. Searches MAST for SPOC 2-minute light curves of TIC 150428135.
  2. Downloads two consecutive sectors (about 54 days).
  3. Uses PDCSAP flux, keeps the pipeline quality flags, normalises each sector
     to a median of 1, and averages onto the game's regular 30-minute grid.
     Grid cells with no measurements are written as null.
  4. Measures the epoch, depth and duration of the 16.05-day signal from the
     data itself with a box least-squares search near the published period.
  5. Writes data/real_data.js with full provenance (target, TIC, mission,
     sectors, cadence, file names, source link, processing steps).

Requires:  pip install lightkurve numpy astropy
Usage:     python tools/prepare_tess_data.py            # first two sectors found
           python tools/prepare_tess_data.py 3 4        # chosen sectors
"""
import json, sys, os
import numpy as np

TIC = "TIC 150428135"
PUBLISHED_PERIOD_C = 16.0511   # days, TOI-700 c (Gilbert et al. 2020); used only to centre the search
GRID_DAYS, STEP = 60.0, 1.0 / 48.0

def main():
    import lightkurve as lk
    res = lk.search_lightcurve(TIC, author="SPOC", exptime=120)
    if len(res) == 0:
        sys.exit("No SPOC 120 s light curves found for " + TIC)
    sectors = sorted(int(s.split()[-1]) for s in res.mission)
    want = [int(a) for a in sys.argv[1:]] or sectors[:2]
    files, t_all, f_all, q_all = [], [], [], []
    for sec in want:
        r = res[np.array([m.endswith(f" {sec:02d}") or m.endswith(f" {sec}") for m in res.mission])]
        lc = r[0].download(flux_column="pdcsap_flux", quality_bitmask="none")
        files.append(os.path.basename(str(lc.meta.get("FILENAME", lc.filename))))
        t = np.asarray(lc.time.value, float); f = np.asarray(lc.flux.value, float); q = np.asarray(lc.quality.value, int)
        ok = np.isfinite(t) & np.isfinite(f)
        f = f / np.nanmedian(f[ok & (q == 0)])
        t_all.append(t[ok]); f_all.append(f[ok]); q_all.append(q[ok])
    t = np.concatenate(t_all); f = np.concatenate(f_all); q = np.concatenate(q_all)
    t0 = t.min(); n = int(round(GRID_DAYS / STEP))
    grid_t = t0 + np.arange(n) * STEP
    flux, quality = [], []
    for g in grid_t:
        m = (t >= g) & (t < g + STEP)
        if m.sum() < 3: flux.append(None); quality.append(0); continue
        good = m & (q == 0)
        if good.sum() >= 3: flux.append(round(float(np.mean(f[good])), 7)); quality.append(0)
        else: flux.append(round(float(np.mean(f[m])), 7)); quality.append(1)
    # epoch, depth and duration from the data (not from a catalogue)
    from astropy.timeseries import BoxLeastSquares
    gt = np.array([g for g, v, qq in zip(grid_t, flux, quality) if v is not None and qq == 0])
    gf = np.array([v for v, qq in zip(flux, quality) if v is not None and qq == 0])
    bls = BoxLeastSquares(gt, gf)
    periods = np.linspace(PUBLISHED_PERIOD_C - 0.3, PUBLISHED_PERIOD_C + 0.3, 600)
    p = bls.power(periods, [0.06, 0.08, 0.1, 0.12])
    i = int(np.argmax(p.power))
    eph = {"name": "Signal 1", "period": round(float(p.period[i]), 4), "t0": round(float(p.transit_time[i] - t0), 4),
           "depthPpm": round(float(p.depth[i] * 1e6)), "durationH": round(float(p.duration[i] * 24), 2)}
    meta = {
        "label": "REAL TESS OBSERVATIONS", "target": "TOI-700", "catalogueId": TIC, "mission": "TESS (NASA)",
        "sector": ", ".join(str(s) for s in want), "cadence": "120 s source, averaged to 30 minutes",
        "fileId": "; ".join(files), "source": "MAST (Mikulski Archive for Space Telescopes), SPOC pipeline",
        "sourceUrl": "https://mast.stsci.edu/portal/Mashup/Clients/Mast/Portal.html?searchQuery=TIC%20150428135",
        "processing": "PDCSAP flux; each sector normalised to median 1; averaged onto a 30-minute grid; grid cells built "
                      "only from flagged cadences are marked as flagged; empty cells left blank. Signal epoch, depth and "
                      "duration measured from these data with a box least-squares search near the published 16.05-day period.",
        "ephemeris": [eph],
    }
    out = {"meta": meta, "time": [round(float(x - t0), 5) for x in grid_t], "flux": flux, "quality": quality}
    path = os.path.join(os.path.dirname(__file__), "..", "data", "real_data.js")
    with open(path, "w") as fh:
        fh.write("// Generated by tools/prepare_tess_data.py from real TESS observations. Do not edit by hand.\n")
        fh.write("window.STARBOUND_REAL_DATA = " + json.dumps(out) + ";\n")
    print("Wrote", os.path.abspath(path)); print("Sectors:", want, "Files:", files); print("Measured signal:", eph)
    print("Open index.html and check that the analysis station badge now reads REAL TESS OBSERVATIONS.")

if __name__ == "__main__":
    main()
