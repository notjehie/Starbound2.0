#!/usr/bin/env python3
"""Scan audio/voice for recordings and write audio/voice/manifest.js. Run after adding or removing files."""
import os, json
d = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "audio", "voice")
ext = (".mp3", ".m4a", ".wav", ".ogg", ".aac", ".webm")
files = sorted(f for f in os.listdir(d) if f.lower().endswith(ext))
with open(os.path.join(d, "manifest.js"), "w") as fh:
    fh.write("// Generated by tools/update_voice_manifest.py\nwindow.STARBOUND_VOICE_FILES = " + json.dumps(files) + ";\n")
print(len(files), "recordings listed")
